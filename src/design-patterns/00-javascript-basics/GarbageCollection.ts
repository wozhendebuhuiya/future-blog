/**
 * 深入理解 JavaScript 的垃圾回收机制 (Garbage Collection, 简称 GC)
 * 
 * 【大白话核心】
 * 内存就像是一个酒店的房间。
 * 你入住（声明变量/创建对象），酒店就给你分配一个房间（分配内存）。
 * 你退房（变量不再使用了），保洁阿姨（垃圾回收器）就会把房间打扫干净，腾出来给下一个人用（释放内存）。
 * 
 * 问题是：保洁阿姨怎么知道你是不是已经“退房”了呢？
 * 
 * 现代浏览器（如 V8 引擎）主要使用一种叫做【标记清除 (Mark-and-Sweep)】的算法。
 */

// ==========================================
// 场景 1：正常的函数执行与回收 (保洁阿姨正常工作)
// ==========================================
function normalFunction() {
  // 1. 酒店分配了一个房间给大对象 data
  const data = {
    name: "我是临时数据",
    size: "很大很大的一块内存..."
  };
  
  console.log("正在使用 data:", data.name);
  
  // 2. 函数执行完毕。
  // 在“标记清除”算法中，保洁阿姨会从全局的“根节点(Root)”开始往下找。
  // 此时，从全局再也找不到任何人能访问到这个 `data` 了（它失去了所有的“引用/联系”）。
  // 3. 结论：保洁阿姨会把 data 标记为“垃圾”，并在下一次打扫时把它清空，释放内存。
}

console.log("\n--- 测试正常回收 ---");
normalFunction();
// 此时，normalFunction 内部的 data 已经被(或即将被)垃圾回收。


// ==========================================
// 场景 2：闭包导致的内存驻留 (保洁阿姨不敢打扫)
// ==========================================
function closureFunction() {
  // 1. 同样分配了房间
  const importantData = {
    name: "我是闭包里的数据",
    secret: "不要回收我！"
  };

  // 2. 但是这里返回了一个函数，并且这个函数“牵着” importantData
  return function() {
    console.log("正在访问闭包数据:", importantData.name);
  };
}

console.log("\n--- 测试闭包内存驻留 ---");
// 3. 把里面返回的函数赋值给了全局变量 `myKey`
const myKey = closureFunction(); 

// 4. 现在保洁阿姨从全局(Root)往下找：
// 全局 -> myKey -> 内部匿名函数 -> importantData
// 保洁阿姨发现：哦！原来这个 importantData 还有一条线连着外面呢！外面可能还要用它！
// 5. 结论：保洁阿姨【绝对不敢】清理 importantData。这就实现了闭包的变量保留。

myKey(); // 正常打印

// 6. 如果你确定以后再也不用这把钥匙了，你应该怎么做？
// 手动切断联系（释放内存）：
// myKey = null; 
// 此时保洁阿姨再找，发现线断了，就会把 importantData 回收掉。


// ==========================================
// 场景 3：为什么以前的旧浏览器会内存泄漏？(了解即可：引用计数法)
// ==========================================
// 很久以前的 IE 浏览器使用的是【引用计数 (Reference Counting)】法。
// 规则很简单：谁牵着我，我的计数就 +1。没牵着我，就是 0，我就被回收。
// 这会导致一个致命问题：【循环引用】
function createCycle() {
  const objA: any = {};
  const objB: any = {};
  
  // A 牵着 B，B 牵着 A
  objA.friend = objB;
  objB.friend = objA;
  
  // 函数结束，虽然外面没人能拿到 objA 和 objB 了，
  // 但因为它们俩互相牵着，引用计数都不为 0！
  // 在旧浏览器里，这两个对象永远不会被回收，导致内存泄漏。
  
  // 现代浏览器的【标记清除】法解决了这个问题：
  // 因为从全局 Root 找不到它俩，哪怕它俩抱得再紧，也会被保洁阿姨一起扔掉。
}
createCycle();
